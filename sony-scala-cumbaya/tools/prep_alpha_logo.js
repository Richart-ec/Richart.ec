// Extracts the α path from the Wikimedia "Sony_Alpha_logo.svg", measures its
// exact bounding box in Chromium (getBBox) and writes tight SVGs + a TS module.
// Usage: node tools/prep_alpha_logo.js <source.svg> <project_dir>
const fs = require('fs');
const path = require('path');
const {chromium} = require('playwright');

const [, , src, project] = process.argv;
const svg = fs.readFileSync(src, 'utf8');
const group = svg.match(/<g[^>]*transform="translate\(([-\d.]+),([-\d.]+)\)"[^>]*fill:#e94e09[^>]*>([\s\S]*?)<\/g>/i);
if (!group) throw new Error('alpha group not found');
const [tx, ty] = [parseFloat(group[1]), parseFloat(group[2])];
const d = group[3].match(/\sd="([^"]+)"/)[1].replace(/\s+/g, ' ').trim();

(async () => {
  const browser = await chromium.launch();
  const page = await browser.newPage();
  await page.setContent(
    `<svg xmlns="http://www.w3.org/2000/svg" width="400" height="300"><g transform="translate(${tx},${ty})"><path id="a" d="${d}"/></g></svg>`,
  );
  const bb = await page.evaluate(() => {
    const p = document.getElementById('a');
    const b = p.getBBox();
    return {x: b.x, y: b.y, width: b.width, height: b.height};
  });
  await browser.close();
  // bbox in path space; add the group translation for the outer space
  const vb = [bb.x + tx, bb.y + ty, bb.width, bb.height].map((v) => +v.toFixed(3));
  const mk = (fill) =>
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vb.join(' ')}" width="${vb[2]}" height="${vb[3]}">\n` +
    `  <g transform="translate(${tx},${ty})"><path fill="${fill}" d="${d}"/></g>\n</svg>\n`;
  fs.writeFileSync(path.join(project, 'public/brand/sony-alpha.svg'), mk('#E94E09'));
  fs.writeFileSync(path.join(project, 'public/brand/sony-alpha-white.svg'), mk('#FFFFFF'));
  const ts =
    `// Generated by tools/prep_alpha_logo.js from Wikimedia Commons File:Sony_Alpha_logo.svg\n` +
    `// (PD-textlogo; Sony trademark). Path space includes the original group translate.\n` +
    `export const ALPHA_VIEWBOX = { x: ${vb[0]}, y: ${vb[1]}, width: ${vb[2]}, height: ${vb[3]} };\n` +
    `export const ALPHA_TRANSLATE = { x: ${tx}, y: ${ty} };\n` +
    `export const ALPHA_PATH = '${d}';\n`;
  fs.writeFileSync(path.join(project, 'src/lib/alphaLogoPath.ts'), ts);
  console.log('viewBox', vb.join(' '));
})();
