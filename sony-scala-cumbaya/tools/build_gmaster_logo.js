// Builds the G MASTER lockup:
//   - emblem rebuilt geometrically (flat top/bottom, parabolic sides as exact
//     quadratic Béziers, small rounded corners) from parameters fitted on the
//     official /lentes-gm banner
//   - G glyph and MASTER wordmark traced with potrace from 12x bitmaps
// Outputs public/brand/gmaster-*.svg and src/lib/gmasterPaths.ts
// Usage: node tools/build_gmaster_logo.js <trace_dir> <project_dir>
const fs = require('fs');
const path = require('path');
const {Potrace} = require('potrace');

const [, , traceDir, project] = process.argv;
const crops = JSON.parse(fs.readFileSync(path.join(traceDir, 'crops.json'), 'utf8'));
const S = crops.scale;
const E = crops.emblem;
const GM_ORANGE = '#CD4902';

const trace = (file) =>
  new Promise((resolve, reject) => {
    const p = new Potrace({
      threshold: 128,
      blackOnWhite: true,
      turdSize: 100,
      // lower alphaMax keeps the stem/bar corners crisp instead of rounding them
      alphaMax: parseFloat(process.env.GM_ALPHAMAX || '0.9'),
      optCurve: true,
      optTolerance: parseFloat(process.env.GM_OPTTOL || '0.4'),
    });
    p.loadImage(file, (err) => {
      if (err) return reject(err);
      const tag = p.getPathTag();
      resolve(tag.match(/\sd="([^"]+)"/)[1]);
    });
  });

// Map an absolute potrace path from bitmap px to banner px.
const mapPath = (d, box) => {
  const letters = new Set(d.match(/[A-Za-z]/g));
  for (const l of letters) if (!'MCLZ'.includes(l)) throw new Error('unexpected command ' + l);
  let i = 0;
  return d
    .replace(/-?\d*\.?\d+/g, (n) => {
      const v = parseFloat(n);
      const out = i % 2 === 0 ? box[0] + v / S : box[1] + v / S;
      i++;
      return out.toFixed(3);
    })
    .replace(/\s+/g, ' ')
    .trim();
};

const emblemPath = (r) => {
  const {cx, cy} = E;
  const hh = E.height / 2;
  const a = E.half_w_mid;
  const t = E.half_w_top;
  const k = (a - t) / (hh * hh);
  const Y = hh - r;
  const xY = a - k * Y * Y; // side x at the end of the corner round
  const xc = a + k * Y * Y; // control point that makes the side an exact parabola
  const f = (v) => v.toFixed(3);
  return [
    `M ${f(cx - t + r)} ${f(cy - hh)}`,
    `L ${f(cx + t - r)} ${f(cy - hh)}`,
    `Q ${f(cx + t)} ${f(cy - hh)} ${f(cx + xY)} ${f(cy - Y)}`,
    `Q ${f(cx + xc)} ${f(cy)} ${f(cx + xY)} ${f(cy + Y)}`,
    `Q ${f(cx + t)} ${f(cy + hh)} ${f(cx + t - r)} ${f(cy + hh)}`,
    `L ${f(cx - t + r)} ${f(cy + hh)}`,
    `Q ${f(cx - t)} ${f(cy + hh)} ${f(cx - xY)} ${f(cy + Y)}`,
    `Q ${f(cx - xc)} ${f(cy)} ${f(cx - xY)} ${f(cy - Y)}`,
    `Q ${f(cx - t)} ${f(cy - hh)} ${f(cx - t + r)} ${f(cy - hh)}`,
    'Z',
  ].join(' ');
};

(async () => {
  const gD = mapPath(await trace(path.join(traceDir, 'g.png')), crops.g_box);
  const mD = mapPath(await trace(path.join(traceDir, 'master.png')), crops.master_box);
  const emD = emblemPath(1.2);

  // Bounds of MASTER (from coordinates; good enough for framing)
  const nums = mD.match(/-?\d*\.?\d+/g).map(Number);
  const mx = nums.filter((_, i) => i % 2 === 0);
  const masterRight = Math.max(...mx);
  const masterLeft = Math.min(...mx);
  const top = E.cy - E.height / 2;
  const emLeft = E.cx - E.half_w_mid;
  const emRight = E.cx + E.half_w_mid;
  const vbFull = [emLeft, top, masterRight - emLeft, E.height].map((v) => +v.toFixed(3));
  const vbEmblem = [emLeft, top, emRight - emLeft, E.height].map((v) => +v.toFixed(3));

  const svg = (vb, masterFill, withMaster) =>
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${vb.join(' ')}" width="${vb[2]}" height="${vb[3]}">\n` +
    `  <path fill="${GM_ORANGE}" d="${emD}"/>\n` +
    `  <path fill="#FFFFFF" d="${gD}"/>\n` +
    (withMaster ? `  <path fill="${masterFill}" d="${mD}"/>\n` : '') +
    `</svg>\n`;
  const brand = path.join(project, 'public/brand');
  fs.writeFileSync(path.join(brand, 'gmaster-logo-dark.svg'), svg(vbFull, '#FFFFFF', true));
  fs.writeFileSync(path.join(brand, 'gmaster-logo-light.svg'), svg(vbFull, '#000000', true));
  fs.writeFileSync(path.join(brand, 'gmaster-emblem.svg'), svg(vbEmblem, '', false));

  const ts =
    `// Generated by tools/build_gmaster_logo.js. Coordinates are banner pixels of\n` +
    `// store.sony.com.ec/lentes-gm (1920x600). Emblem: geometric rebuild; G and MASTER: potrace.\n` +
    `export const GM_ORANGE = '${GM_ORANGE}';\n` +
    `export const GM_VIEWBOX_FULL = { x: ${vbFull[0]}, y: ${vbFull[1]}, width: ${vbFull[2]}, height: ${vbFull[3]} };\n` +
    `export const GM_VIEWBOX_EMBLEM = { x: ${vbEmblem[0]}, y: ${vbEmblem[1]}, width: ${vbEmblem[2]}, height: ${vbEmblem[3]} };\n` +
    `export const GM_MASTER_X = { left: ${masterLeft.toFixed(3)}, right: ${masterRight.toFixed(3)} };\n` +
    `export const GM_EMBLEM_PATH = '${emD}';\n` +
    `export const GM_G_PATH = '${gD}';\n` +
    `export const GM_MASTER_PATH = '${mD}';\n`;
  fs.writeFileSync(path.join(project, 'src/lib/gmasterPaths.ts'), ts);
  console.log('viewBox full', vbFull.join(' '), '| emblem', vbEmblem.join(' '));
  console.log('G path chars', gD.length, 'MASTER path chars', mD.length);
})();
