"""Builds the SONY wordmark assets from Sony's official scene7 SVG.

- public/brand/sony-logo.svg      white wordmark, viewBox cropped to the glyphs
- src/lib/sonyLogoPaths.ts        one path per letter (S, O, N, Y) for animation

Usage: python3 tools/prep_sony_logo.py <source.svg> <project_dir>
"""
import re
import sys
from pathlib import Path

VIEWBOX = (0.979, 0.549, 500.0, 88.03)  # x, y, w, h (glyph bounds, no padding)


def extent(d: str):
    nums = [float(n) for n in re.findall(r"-?\d*\.?\d+(?:e-?\d+)?", d)]
    xs, ys = nums[0::2], nums[1::2]
    return min(xs), max(xs), min(ys), max(ys)


def main(src: str, project: str) -> None:
    svg = Path(src).read_text()
    paths = re.findall(r'<path[^>]*\sd="([^"]+)"', svg)
    if len(paths) != 4:
        raise SystemExit(f"expected 4 paths, found {len(paths)}")
    letters = sorted(paths, key=lambda d: extent(d)[0])
    names = ["S", "O", "N", "Y"]
    x, y, w, h = VIEWBOX

    out_svg = Path(project, "public/brand/sony-logo.svg")
    out_svg.parent.mkdir(parents=True, exist_ok=True)
    body = "\n".join(
        f'  <path id="sony-{n}" fill="#FFFFFF" d="{" ".join(d.split())}"/>'
        for n, d in zip(names, letters)
    )
    out_svg.write_text(
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="{x} {y} {w} {h}" '
        f'width="{w}" height="{h}">\n{body}\n</svg>\n'
    )

    ts_lines = [
        "// Generated by tools/prep_sony_logo.py from Sony's official scene7 SVG.",
        "// Coordinates are in the original glyph space; use SONY_VIEWBOX to frame them.",
        f"export const SONY_VIEWBOX = {{ x: {x}, y: {y}, width: {w}, height: {h} }};",
        "",
        "export type SonyLetter = {",
        "  readonly id: 'S' | 'O' | 'N' | 'Y';",
        "  readonly d: string;",
        "  readonly minX: number;",
        "  readonly maxX: number;",
        "};",
        "",
        "export const SONY_LETTERS: readonly SonyLetter[] = [",
    ]
    for n, d in zip(names, letters):
        x0, x1, _, _ = extent(d)
        ts_lines.append(
            f"  {{ id: '{n}', minX: {x0:.3f}, maxX: {x1:.3f}, d: '{' '.join(d.split())}' }},"
        )
    ts_lines += ["];", ""]
    out_ts = Path(project, "src/lib/sonyLogoPaths.ts")
    out_ts.write_text("\n".join(ts_lines))
    print("wrote", out_svg, "and", out_ts)
    for n, d in zip(names, letters):
        print(n, [round(v, 2) for v in extent(d)])


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
